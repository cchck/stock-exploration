"""Refresh the advisor folder (给导师/) from results/.

给导师/ is what the advisor reads: the report (复现报告.docx, the hand-edited master; it is
not generated by any script), the three paper-vs-ours comparison tables, and the figures
the report shows. The tables and figures are copies of files the replication CLIs write to
results/; results/ stays the single place code writes to, and this script is the only way
the copies are made, so rerun it after rerunning a replication.

Usage: .venv/bin/python scripts/export_advisor.py
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
ADVISOR = ROOT / "给导师"

TABLES = ["lsy_comparison.csv", "allen_comparison.csv", "li_comparison.csv"]
# report figure (original segment) -> name in the advisor folder
FIGURES = {
    "lsy/figures/fig1_shell_size_deciles_original.png": "LSY图1_借壳上市壳公司的规模分布.png",
    "lsy/figures/fig2_shell_value_original.png": "LSY图2_壳价值占市值的比例.png",
    "allen/figures/fig1_2_bhr_original.png": "Allen图1-2_A股买入持有实际收益.png",
    "allen/figures/fig4_st_roa_original.png": "Allen图4_永久ST公司被ST前后的ROA.png",
    "allen/figures/fig5_investment_ncf_original.png": "Allen图5_投资与净现金流.png",
}


def export() -> None:
    for sub, files in (("对照表", {t: t for t in TABLES}), ("图", FIGURES)):
        dest = ADVISOR / sub
        if dest.exists():
            shutil.rmtree(dest)  # no stale files left behind
        dest.mkdir(parents=True)
        for src, name in files.items():
            path = RESULTS / src
            if not path.exists():
                raise FileNotFoundError(f"{path} missing; rerun the replication that writes it")
            shutil.copy2(path, dest / name)
        print(f"{dest.relative_to(ROOT)}: {len(files)} files")


if __name__ == "__main__":
    export()
